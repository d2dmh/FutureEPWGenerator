class Translator:
    def __init__(self, language: str = "en"):
        self.language = language if language in {"en", "zh_CN"} else "en"

    def set_language(self, language: str) -> None:
        self.language = language if language in {"en", "zh_CN"} else "en"

    def text(self, key: str, **kwargs) -> str:
        table = ZH_CN if self.language == "zh_CN" else EN
        template = table.get(key, EN.get(key, key))
        if kwargs:
            try:
                return template.format(**kwargs)
            except Exception:
                return template
        return template


def bind_text(widget, key: str, translator: Translator) -> None:
    """Attach a stable semantic translation key to a Qt text widget."""
    widget.setProperty("i18nKey", key)
    text = translator.text(key)
    if hasattr(widget, "setText"):
        widget.setText(text)
    elif hasattr(widget, "setTitle"):
        widget.setTitle(text)


def retranslate_tree(root, translator: Translator) -> None:
    """Retranslate all descendants previously bound with `bind_text`."""
    try:
        from PySide6.QtWidgets import QWidget
    except Exception:
        return
    widgets = [root] + list(root.findChildren(QWidget))
    for widget in widgets:
        key = widget.property("i18nKey") if hasattr(widget, "property") else None
        if not key:
            continue
        text = translator.text(str(key))
        if hasattr(widget, "setText"):
            widget.setText(text)
        elif hasattr(widget, "setTitle"):
            widget.setTitle(text)
